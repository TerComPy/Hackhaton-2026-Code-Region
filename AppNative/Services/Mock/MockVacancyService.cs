    public Task<List<Vacancy>> GetVacanciesAsync(VacancyFilterOptions? filters = null, HashSet<string>? fitDirections = null)
    {
        IEnumerable<Vacancy> query = AllVacancies;

        if (filters != null)
        {
            if (!string.IsNullOrWhiteSpace(filters.Query))
            {
                var words = filters.Query.Trim().ToLower().Split(' ', StringSplitOptions.RemoveEmptyEntries);
                query = query.Where(j =>
                {
                    var hay = $"{j.Title} {j.Company} {j.City} {j.Summary} {j.Short}".ToLower();
                    return words.All(w => hay.Contains(w));
                });
            }

            if (!string.IsNullOrWhiteSpace(filters.City))
            {
                var city = filters.City.Trim().ToLower();
                query = query.Where(j => j.Format == "Удалённо" || j.City.ToLower().Contains(city));
            }

            if (filters.Formats.Count > 0)
            {
                query = query.Where(j => filters.Formats.Contains(j.Format));
            }

            if (filters.OnlyNoExperience)
            {
                query = query.Where(j => j.Experience == "Без опыта");
            }

            if (filters.Sources.Count > 0)
            {
                query = query.Where(j => filters.Sources.Contains(j.Source));
            }

            if (filters.MinSalary > 0)
            {
                query = query.Where(j => j.Salary != null && j.Salary.Length > 1 && j.Salary[1] >= filters.MinSalary);
            }

            var list = query.ToList();

            if (filters.SortBy == "salary")
            {
                list.Sort((a, b) =>
                {
                    int aSal = a.Salary != null && a.Salary.Length > 1 ? a.Salary[1] : -1;
                    int bSal = b.Salary != null && b.Salary.Length > 1 ? b.Salary[1] : -1;
                    return bSal.CompareTo(aSal);
                });
            }
            else if (filters.SortBy == "fit" && fitDirections != null && fitDirections.Count > 0)
            {
                list.Sort((a, b) =>
                {
                    int aFit = fitDirections.Contains(a.Direction) ? 1 : 0;
                    int bFit = fitDirections.Contains(b.Direction) ? 1 : 0;
                    if (aFit != bFit) return bFit.CompareTo(aFit);
                    return a.Id.CompareTo(b.Id);
                });
            }

            return Task.FromResult(list);
        }

        return Task.FromResult(query.ToList());
    }

    public Task<Vacancy?> GetVacancyByIdAsync(int id)
    {
        return Task.FromResult(AllVacancies.FirstOrDefault(j => j.Id == id));
    }

    public Task<List<JobSource>> GetSourcesAsync()
    {
        var counts = AllVacancies
            .GroupBy(j => j.Source)
            .ToDictionary(g => g.Key, g => g.Count());

        var result = counts.Select(kv => new JobSource
        {
            Name = kv.Key,
            Site = Sources.TryGetValue(kv.Key, out var s) ? s.Site : kv.Key,
            From = Sources.TryGetValue(kv.Key, out var s2) ? s2.From : kv.Key,
            On = Sources.TryGetValue(kv.Key, out var s3) ? s3.On : kv.Key,
            Count = kv.Value
        }).ToList();

        return Task.FromResult(result);
    }

    public Task<List<Vacancy>> GetFeaturedRingJobsAsync()
    {
        int[] ringIds = { 1, 4, 3, 2, 6, 14, 7, 9, 11, 10 };
        var featured = ringIds
            .Select(id => AllVacancies.FirstOrDefault(j => j.Id == id))
            .Where(j => j != null)
            .Select(j => j!)
            .ToList();

        return Task.FromResult(featured);
    }
