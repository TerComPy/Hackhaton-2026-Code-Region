import { test, expect } from '@playwright/test';
for (const theme of ['light', 'dark']) {
 test(`auth and sorting in ${theme}`, async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(t => localStorage.setItem('starter.theme', JSON.stringify(t)), theme);
  await page.goto('/#/account');
  await expect(page.locator('html')).toHaveAttribute('data-theme', theme);
  await page.getByRole('button', {name:'Создать профиль', exact:true}).click();
  await expect(page.locator('.member')).toHaveCount(0);
  await page.locator('#auth-name').fill('Анна');
  await page.locator('#auth-email').fill('invalid');
  await page.locator('#auth-password').fill('short');
  await page.getByRole('button', {name:'Создать профиль', exact:true}).click();
  await expect(page.locator('#auth-email:invalid')).toHaveCount(1);
  await page.locator('#auth-email').fill('anna@example.org');
  await expect(page.locator('#auth-password:invalid')).toHaveCount(1);
  await page.getByRole('button', {name:'Показать пароль',exact:true}).click();
  await expect(page.locator('#auth-password')).toHaveAttribute('type','text');
  await page.getByRole('button', {name:'Скрыть пароль',exact:true}).click();
  await expect(page.locator('#auth-password')).toHaveAttribute('type','password');
  await page.getByRole('button', {name:'Вход',exact:true}).click();
  await expect(page.locator('#auth-name')).toBeHidden();
  await page.getByRole('button',{name:'Регистрация',exact:true}).click();
  await expect(page.locator('#auth-name')).toHaveValue('Анна');
  await page.getByRole('button',{name:'Вход',exact:true}).click();
  await page.locator('#auth-password').fill('password12345');
  await page.getByRole('button',{name:'Войти',exact:true}).click();
  await expect(page.locator('.member')).toBeVisible();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme',theme);
  await expect(page.locator('.member')).toBeVisible();
  await page.goto('/');
  const titles = page.locator('#catalog .job__title');
  const original = await titles.allTextContents();
  const sort = page.getByLabel('Сортировка');
  await expect(sort).toHaveCSS('appearance','none');
  await expect(sort).toHaveCSS('height', info.project.name.startsWith('mobile') ? '48px' : '44px');
  await sort.selectOption('salary');
  await expect.poll(() => titles.allTextContents()).not.toEqual(original);
  await sort.selectOption('date');
  await expect(titles).toHaveText(original);
  await sort.focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await expect(sort).toHaveValue('salary');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
 });
}
